// Precomputed comparison of the two double-spend models (α = 0.2), generated
// with backend/app/probability so both curves reflect the actual math:
//   nakamoto — the whitepaper catch-up probability (confirmations only,
//              nakamoto_double_spend_probability)
//   neumayer — the time-aware model this site uses
//              (p_double_spend_if_accepted_now)
//
// Both are evaluated over the same slow-confirm timeline as the "Slow to
// confirm" example (real block gaps of block 16589, June 2009): conf 1 at
// t=0, conf 2 after ~116 min, conf 3 after ~151 min, then stuck at 3.
// Confirmations are instantaneous, so each one is encoded as a pair of points
// one second apart to draw a vertical drop.

export const COMPARISON_ALPHA = 0.2;

export interface ComparisonPoint {
  elapsed_seconds: number;
  nakamoto: number;
  neumayer: number;
}

function toPoints(rows: number[][]): ComparisonPoint[] {
  return rows.map(([elapsed_seconds, nakamoto, neumayer]) => ({
    elapsed_seconds,
    nakamoto,
    neumayer,
  }));
}

